test('deletion OTP uses CSPRNG, throttled RPC issuance, and atomic consumption', () => {
  const migration = read('supabase/migrations/202610060004_delete_otp_hardening.sql').toLowerCase()
  const send = read('supabase/functions/send-delete-otp/index.ts')
  const deleteAccount = read('supabase/functions/delete-account/index.ts')
  const otp = read('supabase/functions/_shared/delete_otp.ts')
  for (const column of ['attempt_count', 'requested_at', 'locked_until']) assert.match(migration, new RegExp(`add column if not exists ${column}`))
  assert.match(migration, /for\s+update/)
  assert.match(migration, /interval\s+'1 minute'/)
  assert.match(migration, /next_attempts\s+>=\s+5/)
  assert.match(migration, /interval\s+'15 minutes'/)
  assert.match(otp, /crypto\.getRandomValues/)
  assert.match(send, /issueDeleteOtp/)
  assert.doesNotMatch(send, /Math\.random/)
  assert.match(deleteAccount, /consumeDeleteOtp/)
  assert.doesNotMatch(deleteAccount, /from\('mt_delete_otps'\)/)
})
